#!/usr/bin/env bash
# ANDORRA 24: configure existing diagnostic bridge from an EXISTING root-only token file.
# Does not print tokens, reinstall software, alter LIVE VM, or render video.
set -Eeuo pipefail
umask 077
meta(){ curl -fsS -m 5 -H 'Metadata-Flavor: Google' "http://metadata.google.internal/computeMetadata/v1/$1"; }
[[ "$(id -u)" == 0 ]] || { echo "NEED_ROOT"; exit 2; }
[[ "$(meta instance/name)" == "andorra24-runway-runner" && "$(meta project/project-id)" == "andorra-24-live" ]] || { echo "WRONG_INSTANCE_REFUSED"; exit 3; }
DIR=/etc/andorra24-browser-use
SRC="$DIR/bridge.token"
DEST="$DIR/bridge.env"
[[ -f "$SRC" && -s "$SRC" ]] || { echo "TOKEN_FILE_NOT_FOUND: $SRC (no changes made)"; exit 4; }
# Hexadecimal-only token generated by earlier openssl rand -hex 32 (not 'Bearer ').
TOKEN=$(tr -d '\r\n' < "$SRC")
[[ "$TOKEN" =~ ^[0-9a-fA-F]{64}$ ]] || { echo "TOKEN_FORMAT_UNEXPECTED: expected 64-char hex without Bearer prefix (no changes made)"; exit 5; }
[[ -x /opt/andorra24-browser-use/.venv/bin/python ]] || { echo "BRIDGE_VENV_MISSING"; exit 6; }
[[ -f /opt/andorra24-browser-use/bridge.py ]] || { echo "BRIDGE_CODE_MISSING"; exit 7; }
# Avoid inherited incorrect service drop-in from copied instructions.
if [[ -f /etc/systemd/system/andorra24-n8n-bridge.service.d/n8n.conf ]] &&
   grep -q '/etc/andorra24-n8n-bridge.env' /etc/systemd/system/andorra24-n8n-bridge.service.d/n8n.conf; then
    echo "INCOMPATIBLE_OLD_DROPIN: inspect /etc/systemd/system/andorra24-n8n-bridge.service.d/n8n.conf; no changes made"
    exit 8
fi
# Atomic, secret-preserving replacement, not echoed.
TMP=$(mktemp "$DIR/.bridge.env.XXXXXX")
trap 'rm -f "$TMP"' EXIT
chmod 0600 "$TMP"
{
printf 'A24_N8N_PULL_URL=https://blaxxun.app.n8n.cloud/webhook/a24-bridge-pull\n'
printf 'A24_N8N_RESULT_URL=https://blaxxun.app.n8n.cloud/webhook/a24-bridge-result\n'
printf 'A24_N8N_BRIDGE_TOKEN=%s\n' "$TOKEN"
} > "$TMP"
mv -f "$TMP" "$DEST"
unset TOKEN
systemctl daemon-reload
systemctl enable --now andorra24-n8n-bridge.service
systemctl restart andorra24-n8n-bridge.service
sleep 4
systemctl is-active andorra24-n8n-bridge.service
journalctl -u andorra24-n8n-bridge.service -n 8 --no-pager --output=cat | sed -E 's/(Bearer )[a-zA-Z0-9._-]+/\1[REDACTED]/g'
echo "BRIDGE_CONFIGURED_AND_STARTED_DIAGNOSTIC_ONLY"
echo "LIVE_SERVER_UNTOUCHED"
